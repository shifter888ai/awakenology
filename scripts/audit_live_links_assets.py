#!/usr/bin/env python3
"""Probe production URLs referenced by the local integrity inventory.

Requires site-integrity-report.csv generated by audit_site_integrity.py.
Outputs live-link-asset-report.csv. Network failures are recorded, not hidden.
"""
import argparse
import csv
import time
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path
from urllib.parse import quote, urldefrag, urljoin, urlsplit, urlunsplit

ROOT = Path(__file__).resolve().parents[1]
DOMAIN = "https://awakenology.space"
SOURCE_REPORT = ROOT / "site-integrity-report.csv"
OUT = ROOT / "live-link-asset-report.csv"
UA = "Awakenology-Link-Asset-Audit/1.0 (+https://awakenology.space/)"
SKIP = ("#", "data:", "javascript:", "mailto:", "tel:", "sms:")

def source_base(source):
    if source == "index.html":
        return DOMAIN + "/"
    if source.endswith("/index.html"):
        return DOMAIN + "/" + source[:-len("index.html")]
    return DOMAIN + "/" + source

def make_url(source, reference):
    ref = (reference or "").strip()
    if not ref or ref.lower().startswith(SKIP):
        return ""
    base = source_base(source)
    absolute = urljoin(base, ref)
    parts = urlsplit(absolute)
    if parts.scheme not in ("http", "https") or parts.netloc.lower() not in {"awakenology.space", "www.awakenology.space"}:
        return ""
    # Fragments do not affect the HTTP resource; preserve query strings.
    absolute, _ = urldefrag(absolute)
    p = urlsplit(absolute)
    path = quote(p.path, safe="/%:@!$&'()*+,;=-._~")
    return urlunsplit((p.scheme, p.netloc, path, p.query, ""))

def request_url(url, kind, timeout):
    headers = {"User-Agent": UA, "Accept": "*/*"}
    method = "HEAD" if kind == "asset" else "GET"
    req = urllib.request.Request(url, headers=headers, method=method)
    try:
        with urllib.request.urlopen(req, timeout=timeout) as response:
            status = response.status
            content_type = response.headers.get("Content-Type", "")
            final_url = response.geturl()
            if method == "HEAD" and status in (405, 501):
                raise urllib.error.HTTPError(url, status, "HEAD unsupported", response.headers, None)
            if method == "GET":
                response.read(1024)
            return status, content_type, final_url, ""
    except urllib.error.HTTPError as exc:
        if method == "HEAD" and exc.code in (403, 405, 501):
            try:
                req = urllib.request.Request(url, headers=headers, method="GET")
                with urllib.request.urlopen(req, timeout=timeout) as response:
                    response.read(1024)
                    return response.status, response.headers.get("Content-Type", ""), response.geturl(), ""
            except Exception as retry:
                return getattr(retry, "code", ""), "", "", type(retry).__name__
        return exc.code, exc.headers.get("Content-Type", "") if exc.headers else "", exc.geturl(), ""
    except Exception as exc:
        return "", "", "", type(exc).__name__

def classify_response(url, kind, status, content_type, final_url, error):
    """Classify a probe without confusing redirects, request errors, or HTML asset fallbacks."""
    if error or not isinstance(status, int):
        return "REQUEST_ERROR"
    if status < 200 or status >= 400:
        return "HTTP_ERROR"
    if final_url and final_url.rstrip("/") != url.rstrip("/"):
        return "REDIRECT"
    media_type = (content_type or "").split(";", 1)[0].strip().lower()
    if kind == "asset" and media_type in {"text/html", "application/xhtml+xml"}:
        return "CONTENT_TYPE_MISMATCH"
    return "PASS"

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--workers", type=int, default=8)
    ap.add_argument("--timeout", type=int, default=15)
    ap.add_argument("--strict", action="store_true", help="exit non-zero for HTTP errors, request failures, and asset content-type mismatches")
    args = ap.parse_args()
    if not SOURCE_REPORT.exists():
        print("FAIL: site-integrity-report.csv is missing; run scripts/audit_site_integrity.py first")
        return 2
    with SOURCE_REPORT.open(encoding="utf-8", newline="") as f:
        refs = list(csv.DictReader(f))
    unique = {}
    for row in refs:
        if row.get("status") not in {"PASS"}:
            continue
        url = make_url(row.get("source", ""), row.get("reference", ""))
        if not url:
            continue
        kind = "asset" if row.get("kind") == "asset" or row.get("kind", "").startswith("css-") else "link"
        unique.setdefault(url, {"url":url, "kind":kind, "sources":set(), "references":set()})
        unique[url]["sources"].add(row.get("source", ""))
        unique[url]["references"].add(row.get("reference", ""))
        if kind == "link":
            unique[url]["kind"] = "link"
    print(f"Unique production URLs to probe: {len(unique)}")
    results = []
    with ThreadPoolExecutor(max_workers=max(1, min(args.workers, 16))) as pool:
        futures = {pool.submit(request_url, item["url"], item["kind"], args.timeout): url for url, item in unique.items()}
        for future in as_completed(futures):
            url = futures[future]
            status, content_type, final_url, error = future.result()
            result = classify_response(url, item["kind"], status, content_type, final_url, error)
            item = unique[url]
            results.append({"url":url,"kind":item["kind"],"http_status":status,"content_type":content_type,
                "final_url":final_url,"result":result,"error":error,
                "referenced_by_count":len(item["sources"]),
                "referenced_by":";".join(sorted(item["sources"])),
                "source_references":";".join(sorted(item["references"]))})
    results.sort(key=lambda row:(row["result"] != "HTTP_ERROR", row["result"] != "REQUEST_ERROR", row["url"]))
    fields=["url","kind","http_status","content_type","final_url","result","error","referenced_by_count","referenced_by","source_references"]
    with OUT.open("w",encoding="utf-8",newline="") as f:
        writer=csv.DictWriter(f,fieldnames=fields); writer.writeheader(); writer.writerows(results)
    failed=sum(r["result"] in {"HTTP_ERROR","REQUEST_ERROR","CONTENT_TYPE_MISMATCH"} for r in results)
    mismatches=sum(r["result"]=="CONTENT_TYPE_MISMATCH" for r in results)
    redirects=sum(r["result"]=="REDIRECT" for r in results)
    passed=sum(r["result"]=="PASS" for r in results)
    print(f"Live resources: {len(results)}; passed: {passed}; redirects: {redirects}; content-type mismatches: {mismatches}; failures: {failed}")
    print(f"Report: {OUT.name}")
    for row in [r for r in results if r["result"] in {"HTTP_ERROR","REQUEST_ERROR","CONTENT_TYPE_MISMATCH"}][:40]:
        print(f'{row["result"]}: {row["http_status"]} {row["url"]} (referenced by {row["referenced_by_count"]} source(s))')
    if failed > 40: print(f"... plus {failed-40} more; see CSV report")
    return 1 if args.strict and failed else 0

if __name__ == "__main__":
    raise SystemExit(main())
